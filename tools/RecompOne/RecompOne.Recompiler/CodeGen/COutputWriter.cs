using System.Text;
using System.Text.RegularExpressions;
using RecompOne.Recompiler.Analysis;
using RecompOne.Recompiler.Psx;

namespace RecompOne.Recompiler.CodeGen;

/// <summary>
/// File layout of the C output (see docs/recompiler-c-output.md):
///     {Game}.h            prototypes of every function and hook, overlay/game externs
///     {Game}_{overlay}.c  one per overlay: functions and its address table
///     {Game}_game.c       boot executable, entry and overlay list
/// Every symbol carries the game prefix so several games link into one program.
/// </summary>
public static class COutputWriter
{
    public static string OverlaySymbol(string className, string overlay) =>
        $"{className}_overlay_{Regex.Replace(overlay, "[^A-Za-z0-9_]", "_")}";

    public static void WriteOverlay(string className, string overlayName, IEnumerable<MipsFunction> funcs,
        Func<MipsFunction, string> emit, int lbaStart, uint ovlBase, uint ovlSize, string outDir)
    {
        var sb = new StringBuilder();
        sb.AppendLine("/* Generated by RecompOne. Do not edit. */");
        sb.AppendLine($"#include \"{className}.h\"");
        sb.AppendLine();
        var ordered = funcs.OrderBy(f => f.Start).ToList();
        foreach (var func in ordered)
        {
            sb.Append(emit(func));
            sb.AppendLine();
        }
        var callable = ordered.Where(f => !f.IsStub).ToList();
        string table = $"{OverlaySymbol(className, overlayName)}_functions";
        sb.AppendLine($"static const RecompFunction {table}[] = {{");
        foreach (var func in callable)
            sb.AppendLine($"    {{ 0x{func.Start:X8}u, {className}_{func.EmittedName} }},");
        if (callable.Count == 0) sb.AppendLine("    { 0u, 0 },");
        sb.AppendLine("};");
        sb.AppendLine($"const RecompOverlay {OverlaySymbol(className, overlayName)} = {{ \"{overlayName}\", {lbaStart}, " +
                      $"0x{ovlBase:X8}u, 0x{ovlSize:X}u, {table}, {callable.Count} }};");
        File.WriteAllText(Path.Combine(outDir, $"{className}_{overlayName}.c"), sb.ToString());
    }

    public static void WriteGame(string className, PsxExe exe, string bootExe, string? mainFunction,
        List<string> overlays, List<MipsFunction> allFuncs, string outDir)
    {
        var lang = Dialect.C;

        // Hooks: pre-hooks and conditional instruction hooks answer yes/no; the rest
        // (replacements, post-hooks, instruction observers) return nothing.
        // Kind is "replace", "pre", "post", "instruction" or "branch"; pre and branch return int.
        var hooks = new SortedDictionary<string, (string Kind, string Target)>(StringComparer.Ordinal);
        static bool Returns(string kind) => kind is "pre" or "branch";
        void Hook(string target, string kind)
        {
            string name = lang.HookName(target);
            if (hooks.TryGetValue(name, out var seen))
            {
                if (seen.Target != target)
                    throw new InvalidDataException($"C hook name {name} is used by both {seen.Target} and {target}");
                if (seen.Kind != kind && (Returns(seen.Kind) || Returns(kind)))
                    throw new InvalidDataException($"{target} is used both as a {seen.Kind} and a {kind} hook");
                return;
            }
            hooks[name] = (kind, target);
        }
        foreach (var f in allFuncs)
        {
            if (f.IsPatch) Hook(f.PatchTarget, "replace");
            foreach (var pre in f.PreHookTargets) Hook(pre, "pre");
            foreach (var post in f.PostHookTargets) Hook(post, "post");
            foreach (var list in f.InstructionHookTargets.Values) foreach (var t in list) Hook(t, "instruction");
            foreach (var list in f.InstructionBranchHooks.Values) foreach (var bh in list) Hook(bh.Target, "branch");
        }

        var h = new StringBuilder();
        h.AppendLine("/* Generated by RecompOne. Do not edit. */");
        h.AppendLine("#pragma once");
        h.AppendLine("#include \"recomp.h\"");
        h.AppendLine();
        h.AppendLine("/* Recompiled functions */");
        foreach (var f in allFuncs.OrderBy(f => f.OverlayName, StringComparer.Ordinal).ThenBy(f => f.Start))
            h.AppendLine($"void {className}_{f.EmittedName}(CpuContext *c);");
        h.AppendLine();
        h.AppendLine("/* Hooks and replacements the platform provides (configuration targets) */");
        foreach (var (name, hook) in hooks)
            h.AppendLine($"{(Returns(hook.Kind) ? "int" : "void")} {name}(CpuContext *c); /* {hook.Kind}: {hook.Target} */");
        h.AppendLine();
        foreach (var o in overlays)
            h.AppendLine($"extern const RecompOverlay {OverlaySymbol(className, o)};");
        h.AppendLine($"extern const RecompGame {className}_game;");
        File.WriteAllText(Path.Combine(outDir, $"{className}.h"), h.ToString());

        var g = new StringBuilder();
        g.AppendLine("/* Generated by RecompOne. Do not edit. */");
        g.AppendLine($"#include \"{className}.h\"");
        g.AppendLine();
        g.AppendLine($"static const RecompOverlay *const {className}_overlays[] = {{");
        foreach (var o in overlays) g.AppendLine($"    &{OverlaySymbol(className, o)},");
        g.AppendLine("};");
        g.AppendLine($"const RecompGame {className}_game = {{");
        g.AppendLine($"    \"{className}\", \"{bootExe.Replace("\\", "\\\\")}\",");
        g.AppendLine($"    0x{exe.Destination:X8}u, {exe.TextSize}u, 0x{exe.InitialGP:X8}u, 0x{exe.InitialSP:X8}u, 0x{exe.InitialPC:X8}u,");
        g.AppendLine($"    {mainFunction ?? "0"},");
        g.AppendLine($"    {className}_overlays, {overlays.Count}");
        g.AppendLine("};");
        File.WriteAllText(Path.Combine(outDir, $"{className}_game.c"), g.ToString());
    }
}
