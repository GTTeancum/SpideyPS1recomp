#!/usr/bin/env python3
"""Write default bodies for every hook a game's generated header declares that the
Xbox sources for that game (xbox/runtime, and xbox/src without the other game's
*_smN.c files) do not define yet.

    python -I xbox/tools/gen_hook_defaults.py spiderman|spiderman2

Defaults report the hook as missing the first time it runs, then behave as if it
were absent: a pre-hook lets the original function run, a branch hook does not
branch, anything else does nothing. Output: xbox/build/hooks_default_<game>.c (each
game is its own XBE; see the Makefile's GAME).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

XBOX = Path(__file__).resolve().parents[1]
DECL = re.compile(r"^(?:int|void) (hook_\w+)\(CpuContext \*c\); /\* (\w+): (.+) \*/$")


TAGS = {"spiderman": "sm1", "spiderman2": "sm2"}


def defined_in_sources(game: str) -> set[str]:
    names = set()
    body = re.compile(r"^(?:int|void)\s+(hook_\w+)\s*\(\s*CpuContext\s*\*\s*c\s*\)\s*(?:\{|$)", re.M)
    others = [t for g, t in TAGS.items() if g != game]
    for folder in ("src", "runtime"):
        for path in (XBOX / folder).glob("*.c"):
            if any(path.stem.endswith("_" + t) for t in others):
                continue
            names.update(body.findall(path.read_text(encoding="utf-8", errors="replace")))
    return names


def main() -> int:
    games = sys.argv[1:]
    if len(games) != 1 or games[0] not in TAGS:
        print(__doc__)
        return 1
    hooks: dict[str, tuple[str, str]] = {}
    for game in games:
        for header in (XBOX / "generated" / game).glob("*.h"):
            for line in header.read_text(encoding="utf-8").splitlines():
                m = DECL.match(line.strip())
                if m:
                    name, kind, target = m.groups()
                    if name in hooks and (hooks[name][0] in ("pre", "branch")) != (kind in ("pre", "branch")):
                        raise SystemExit(f"{name} has different signatures across games")
                    hooks.setdefault(name, (kind, target))
    done = defined_in_sources(games[0])
    out = [
        "/* Generated by xbox/tools/gen_hook_defaults.py. Do not edit. */",
        '#include "runtime.h"',
        "",
    ]
    # Some of these run for every mesh drawn (the PC's tracing hooks): after the first
    # call each keeps its own counter instead of searching the missing list by name.
    def count(kind: str, target: str) -> str:
        return f'static unsigned *n; if (n) ++*n; else n = rt_missing(\"{kind} hook\", \"{target}\");'

    missing = 0
    for name, (kind, target) in sorted(hooks.items()):
        if name in done:
            continue
        missing += 1
        if kind in ("pre", "branch"):
            value = 1 if kind == "pre" else 0
            out.append(f"int {name}(CpuContext *c) {{ (void)c; {count(kind, target)} return {value}; }}")
        else:
            out.append(f"void {name}(CpuContext *c) {{ (void)c; {count(kind, target)} }}")
    text = "\n".join(out) + "\n"
    build = XBOX / "build"
    build.mkdir(exist_ok=True)
    (build / f"hooks_default_{games[0]}.c").write_text(text, encoding="utf-8")
    print(f"{len(hooks)} hooks, {len(hooks) - missing} implemented, {missing} defaults written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
