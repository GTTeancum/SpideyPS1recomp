#!/usr/bin/env python3
"""List the GTE command words the generated game code issues, for runtime/gte_ops.h.

    python -I xbox/tools/gen_gte_ops.py

Every call in the generated C passes a constant command word. runtime/gte.c compiles
one routine per listed word with its shift, saturation, matrix and vector choices
fixed, and recomp.h's gte_execute picks that routine at compile time. A word missing
from the list still works through the general routine, only slower; re-run after
regenerating the game code.
"""
import re
from pathlib import Path

XBOX = Path(__file__).resolve().parents[1]


def main() -> int:
    words = set()
    for path in sorted((XBOX / "generated").glob("*/*.c")):
        words.update(m.upper() for m in re.findall(r"gte_execute\(0x([0-9A-Fa-f]{8})u?\)", path.read_text(encoding="utf-8")))
    lines = [
        "/* Generated by xbox/tools/gen_gte_ops.py: the GTE command words the generated game",
        " * code issues (see that script). */",
        "#define GTE_OPS(X) \\",
    ]
    lines += [f"    X({w}) \\" for w in sorted(words)]
    lines.append("")
    (XBOX / "runtime" / "gte_ops.h").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(words)} command words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
